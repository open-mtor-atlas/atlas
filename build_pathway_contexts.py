FLIP = {"active": "suppressed", "suppressed": "active"}


def mirror(d, overrides):
    out = {}
    for k, v in d.items():
        if k in overrides:
            if overrides[k] is not None:
                out[k] = overrides[k]
            continue
        out[k] = FLIP.get(v, v)
    return out


