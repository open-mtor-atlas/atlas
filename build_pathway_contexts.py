"""
build_pathway_contexts.py
Generates pathway/contexts.json, a state-overlay on top of pathway/model.json.

WHY A SEPARATE FILE (not model.json)
model.json is the single source of truth for pathway BIOLOGY (nodes,
interactions, routes, loops) and must never be hand-edited -- see
build_pathway_model.py. Context weighting is a different kind of claim:
"how active is this already-curated interaction under Fed / Fasting /
Exercise", not "does this interaction exist". Keeping it in its own file
means model.json stays untouched and contexts.json can be regenerated,
diffed and validated independently.

STATE VOCABULARY (per edge / per node, within one context)
  active      -- this arm is currently firing / this node is up-weighted
  suppressed  -- this arm is currently quiet / this node is down-weighted
  unclear     -- genuinely ambiguous or under-characterised in this state,
                 NOT the same as "suppressed" -- see epistemic-labelling-pass
  (absent)    -- not evaluated for this context; renders identically to
                 today's baseline (folded into the existing .dim mechanism
                 in pathway.js, not a new visual channel)

ENCODING RULE (why this file only carries state, never colour/shape)
Pathway edge colour is reserved for EFFECT (--pw-act/--pw-inh/--pw-req/
--pw-bind) and dash-pattern+width is reserved for CERTAINTY (directness x
mechanistic confidence) -- see tier-palette-rule. Context state must not
collide with either, so pathway.js renders it as a separate underlay layer
(solid/dashed/dotted, neutral ink colour) plus a small text badge on nodes.
This file only ever emits the abstract state string; all rendering
decisions live in pathway.js.

FASTING is generated by MECHANICALLY MIRRORING Fed (active<->suppressed,
na/unclear untouched) rather than hand-curated a second time. This is a
deliberate simplification, documented here and in the on-page brief: it
models Fed and Fasting as the same fixed network with opposite arms lit,
which is the correct first-order reading for the arms curated below. Any
edge where that mirror is NOT a fair reading of the literature should be
special-cased in FASTING_OVERRIDE below rather than silently mirrored.

Exercise is NOT mirrored -- it is hand-curated because AMPK/mechanical
stress and the GF/AA arm do not sit at opposite ends of one axis the way
Fed/Fasting do.
"""
